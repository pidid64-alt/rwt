"""Модуль «Выпуск 13Б»: литеральные расчёты методики (реле РНТ-565 / ДЗТ-11) и соответствие физических критериев современной функции 87T.

Назначение:
  1. Контрольные примеры Выпуска 13Б (пп. 2.3.1, 2.3.2, 3.3.2) — автоматические тесты (rza/calc/selftest.py, tests/data/b13_examples.json).
  2. Режим «13Б vs современная РЗА»: какой физический критерий 13Б реализуется какой функцией/параметром терминала.
     Автоматическая эквивалентность электромеханического реле и цифровой функции НЕ утверждается — показывается соответствие критерия
     и требуется инженерное обоснование.
"""
from __future__ import annotations

import math

from ..normative import registry
from ..trace import Trace, Var

SQ3 = math.sqrt(3.0)


def rnt565_two_winding(inp: dict) -> dict:
    """Расчёт дифференциальной защиты двухобмоточного трансформатора с реле РНТ-565 по Вып. 13Б (пп. 2.1–2.2, пример 2.3.1).

    inp: s_mva, u_main_kv, u_other_kv, dU (половина диапазона регулирования), ik_max_a (ток внешнего КЗ, приведён к основной стороне),
         ik2_min_a (минимальный ток двухфазного КЗ в зоне, основная сторона), k_i_main, k_i_other (коэф. трансформации ТТ),
         ksx_main, ksx_other (коэффициенты схемы), eps, k_aper, k_odn, k_ots, k_inrush, k_vyg, f_sr, ct_ratio_note.
    """
    reg = registry()
    t = Trace(reg.formulas, "Дифференциальная защита с реле РНТ-565 (Вып. 13Б, пример 2.3.1)")
    g = inp.get
    s = g("s_mva")
    i_main = s * 1000 / (SQ3 * g("u_main_kv"))
    i_other = s * 1000 / (SQ3 * g("u_other_kv"))
    i2_main = i_main * g("ksx_main", SQ3) / g("k_i_main")
    i2_other = i_other * g("ksx_other", 1.0) / g("k_i_other")
    t.note("Первичные и вторичные токи плеч", f"I_ном.осн = {i_main:.2f} А; I_ном.неосн = {i_other:.1f} А; вторичные токи в плечах: {i2_main:.2f} А и {i2_other:.2f} А", "Вып. 13Б п. 2.2.1")
    ik = g("ik_max_a")
    i1 = t.calc("B13.2.4", {"k_апер": g("k_aper", 1.0), "k_одн": g("k_odn", 1.0), "eps": g("eps", 0.1), "I_к_макс": ik}, title="I′нб.расч")
    i2 = t.calc("B13.2.5", {"dU_a": g("dU"), "k_ток_a": 1.0, "dU_b": 0.0, "k_ток_b": 0.0, "I_к_макс": ik}, title="I″нб.расч (двухобмоточный: ΔU·I_к.макс)")
    i_nb12 = Var("I_нб_без_3", i1.value + i2.value, "А")
    c1 = t.calc("B13.2.1", {"k_отс": g("k_ots", 1.3), "I_нб_расч": i_nb12}, title="I_с.з по (2.1)")
    c2 = t.calc("B13.2.2", {"k": g("k_inrush", 1.3), "k_выг": g("k_vyg", 1.0), "I_ном": i_main}, title="I_с.з по (2.2)")
    i_sz = max(c1.value, c2.value)
    i_sr = i_sz * g("ksx_main", SQ3) / g("k_i_main")
    w_calc = t.calc("B13.2.18", {"F_ср": g("f_sr", 100.0), "I_ср_осн": i_sr}, title="w_осн.расч (2.18)")
    w_main = math.floor(w_calc.value + 1e-9)
    w_oth_calc = t.calc("B13.2.20", {"w_осн": w_main, "I_осн_в": i2_main, "I_неосн_в": i2_other}, title="w_неосн.расч (2.20)")
    w_oth = round(w_oth_calc.value)
    i3 = t.calc("B13.2.6", {"w_расч": w_oth_calc, "w_прин": w_oth, "k_ток": 1.0, "I_к_макс": ik}, title="I‴нб.расч (2.6)")
    i_nb = t.calc("B13.2.3", {"I_нб1": i1, "I_нб2": i2, "I_нб3": i3}, title="I_нб.расч (2.3)")
    i_final = t.calc("B13.2.25", {"F_ср": g("f_sr", 100.0), "w": w_main, "K_I": g("k_i_main"), "k_сх": g("ksx_main", SQ3)}, title="I_с.з по принятому числу витков")
    k_ots_fin = i_final.value / i_nb.value
    kch_pre = t.calc("B13.2.26", {"I_к_мин": g("ik2_min_a"), "I_с_з": Var("I_с.з", i_sz, "А")}, title="k_ч предварительный (2.26)")
    kch = t.calc("B13.2.26", {"I_к_мин": g("ik2_min_a"), "I_с_з": i_final}, title="k_ч окончательный (2.26)")
    return {"I_ном_осн": i_main, "I_ном_неосн": i_other, "I_нб1": i1.value, "I_нб2": i2.value, "I_нб12": i_nb12.value, "I_сз_2_1": c1.value, "I_сз_2_2": c2.value,
            "I_сз_предв": i_sz, "I_ср_осн": i_sr, "w_осн_расч": w_calc.value, "w_осн": w_main, "w_неосн_расч": w_oth_calc.value, "w_неосн": w_oth,
            "I_нб3": i3.value, "I_нб_расч": i_nb.value, "I_сз_итог": i_final.value, "k_отс_итог": k_ots_fin, "k_ч_предв": kch_pre.value, "k_ч": kch.value, "trace": t}


def optimal_voltage_two_winding(inp: dict) -> dict:
    """Расчёт по оптимальному напряжению регулируемой обмотки (Вып. 13Б п. 2.1.4, пример 2.3.2)."""
    reg = registry()
    t = Trace(reg.formulas, "Оптимальное напряжение (Вып. 13Б п. 2.1.4)")
    g = inp.get
    dU_opt = t.calc("B13.2.11", {"dU_диап": g("dU_range"), "eps": g("eps", 0.1), "I_к_минус": g("ik_minus_a"), "I_к_плюс": g("ik_plus_a")}, title="ΔU_опт (2.11)")
    u_opt = t.calc("B13.2.8", {"dU_max_пл": g("dU_max_plus"), "dU_опт": dU_opt, "U_ном_ср": g("u_nom_mid_kv")}, title="U_опт (2.8)")
    i12 = t.calc("B13.2.13", {"eps": g("eps", 0.1), "dU_опт": dU_opt, "I_к_плюс": g("ik_plus_a")}, title="I′нб + I″нб (2.13)")
    i_sz = t.calc("B13.2.1", {"k_отс": g("k_ots", 1.3), "I_нб_расч": i12}, title="I_с.з по (2.1)")
    i_nom_opt = g("s_mva") * 1000 / (SQ3 * u_opt.value)
    return {"dU_опт": dU_opt.value, "U_опт": u_opt.value, "I_нб12": i12.value, "I_сз": i_sz.value, "I_ном_опт": i_nom_opt, "trace": t}


def dzt11_min_current(inp: dict) -> dict:
    """ДЗТ-11: минимальный ток срабатывания по броску (3.2.3) и первичный ток по числу витков (пример 3.3.2)."""
    g = inp.get
    i_min = g("k") * g("k_vyg", 1.0) * g("i_nom_a")
    i_sz = g("f_sr", 100.0) / g("w_main") * g("k_i_main") / g("ksx_main", SQ3)
    return {"I_сз_мин": i_min, "I_сз_по_виткам": i_sz}



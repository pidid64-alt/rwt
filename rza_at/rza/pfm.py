def get(pid: str) -> PFMParam:
    return PFM[pid]


def catalog() -> list[dict]:
    return [p.to_dict() for p in PFM.values()]


def by_function(fid: str) -> list[PFMParam]:
    return [p for p in PFM.values() if p.function == fid]


def key(pid: str, instance: str = "") -> str:
    return f"{pid}@{instance}" if instance else pid


def split_key(k: str) -> tuple[str, str]:
    pid, _, inst = k.partition("@")
    return pid, inst
